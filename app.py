import streamlit as st
import pandas as pd
st.title("Streamlit Application")

st.header("Welcome to the Streamlit App")
st.subheader("This is a simple Streamlit application.")
st.write("Feel free to explore the features of Streamlit!")
st.text("This is a text element.")

df= pd.DataFrame({
    'Name': ['Alice', 'Bob', 'Charlie', 'David'],
    'Age': [25, 30, 35, 40],
    'City': ['New York', 'Los Angeles', 'Chicago', 'Houston']
})
st.table(df)
st.bar_chart(df, x='Name', y='Age')




@st.dialog("Cast your vote")
def vote(item):
    st.write(f"Why is {item} your favorite?")
    reason = st.text_input("Because...")
    if st.button("Submit"):
        st.session_state.vote = {"item": item, "reason": reason}
        st.rerun()

if "vote" not in st.session_state:
    st.write("Vote for your favorite")
    if st.button("A"):
        vote("A")
    if st.button("B"):
        vote("B")
else:
    f"You voted for {st.session_state.vote['item']} because {st.session_state.vote['reason']}"


